import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const output = path.join(root, 'src/game.bundle.js');

// These three modules only use named exports and single-line local imports.
// Keep the testable source modules; ship a classic script for file:// browsers.
export async function buildBundle() {
  const sources = await Promise.all(['engine', 'art', 'main'].map(async name => {
    const source = await readFile(path.join(root, `src/${name}.js`), 'utf8');
    const script = source
      .replace(/^import \{[^\n]+\} from '\.\/[^']+';\r?\n/gm, '')
      .replace(/^export (?=(?:const|let|function)\b)/gm, '');
    if (/^\s*(?:import|export)\s/m.test(script)) throw new Error(`Unsupported module syntax in ${name}.js`);
    return `// src/${name}.js\n${script.trim()}`;
  }));
  return `// Generated by npm run build. Edit engine.js, art.js, or main.js instead.\n// Classic script: works from file:// without a server or module imports.\n(() => {\n'use strict';\n\n${sources.join('\n\n')}\n})();\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const bundle = await buildBundle();
  if (process.argv.includes('--check')) {
    if (await readFile(output, 'utf8').catch(() => '') !== bundle) {
      console.error('The browser bundle is out of date. Run npm run build.');
      process.exitCode = 1;
    }
  } else {
    await writeFile(output, bundle);
    console.log('Built src/game.bundle.js — ready for offline file:// play.');
  }
}
